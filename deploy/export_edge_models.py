"""
Edge Model Exporter for TinyML & Embedded Microcontrollers.
Exports trained Lightweight Autoencoder to:
1. TorchScript (.pt) for PyTorch Mobile / Edge Gateway deployment
2. ONNX (.onnx) for TensorRT / OpenVINO / ONNXRuntime edge devices
3. C Header file (.h) with raw float/int8 weight matrices for bare-metal C/C++ microcontrollers
   (STM32, ESP32, ARM Cortex-M)
"""

import os
import sys
import json
import torch
import numpy as np

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from models.lightweight_autoencoder import build_model


def export_torchscript(model: torch.nn.Module, sample_input: torch.Tensor, out_path: str) -> str:
    """Exports model to optimized TorchScript format."""
    model.eval()
    traced_model = torch.jit.trace(model, sample_input)
    traced_model.save(out_path)
    size_kb = os.path.getsize(out_path) / 1024.0
    print(f"[OK] TorchScript exported to: {out_path} ({size_kb:.2f} KB)")
    return out_path


def export_onnx(model: torch.nn.Module, sample_input: torch.Tensor, out_path: str) -> str:
    """Exports model to ONNX format."""
    model.eval()
    try:
        torch.onnx.export(
            model,
            sample_input,
            out_path,
            export_params=True,
            opset_version=14,
            do_constant_folding=True,
            input_names=["sensor_window"],
            output_names=["reconstructed_window"],
            dynamic_axes={"sensor_window": {0: "batch_size"}, "reconstructed_window": {0: "batch_size"}},
        )
        size_kb = os.path.getsize(out_path) / 1024.0
        print(f"[OK] ONNX model exported to: {out_path} ({size_kb:.2f} KB)")
        return out_path
    except Exception as e:
        print(f"[Warning] ONNX export notice: {e}")
        return ""


def export_c_header(model: torch.nn.Module, threshold: float, out_path: str) -> str:
    """
    Exports model weights, biases, and anomaly threshold into a standalone C header file.
    Enables zero-dependency execution on bare-metal microcontrollers (ARM Cortex-M, STM32, ESP32).
    """
    state_dict = model.state_dict()
    
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("/**\n")
        f.write(" * Autonomous Edge Anomaly Detector - Microcontroller Model Weights\n")
        f.write(" * Auto-generated by TinyML Exporter for IoT Security Framework\n")
        f.write(" * Target: STM32, ESP32, ARM Cortex-M4/M7, Arduino Nano 33 BLE\n")
        f.write(" */\n\n")
        f.write("#ifndef IOT_ANOMALY_MODEL_H\n")
        f.write("#define IOT_ANOMALY_MODEL_H\n\n")
        f.write(f"#define ANOMALY_WINDOW_SIZE 16\n")
        f.write(f"#define ANOMALY_NUM_SENSORS 8\n")
        f.write(f"#define ANOMALY_INPUT_DIM (ANOMALY_WINDOW_SIZE * ANOMALY_NUM_SENSORS)\n")
        f.write(f"#define ANOMALY_THRESHOLD_MSE {threshold:.6f}f\n\n")

        for key, tensor in state_dict.items():
            clean_name = key.replace(".", "_")
            flat_arr = tensor.cpu().detach().numpy().flatten()
            f.write(f"// Tensor: {key} (Shape: {list(tensor.shape)})\n")
            f.write(f"static const float {clean_name}[{len(flat_arr)}] = {{\n    ")
            for i, val in enumerate(flat_arr):
                f.write(f"{val:.6f}f, ")
                if (i + 1) % 8 == 0:
                    f.write("\n    ")
            f.write("\n};\n\n")

        f.write("#endif // IOT_ANOMALY_MODEL_H\n")

    size_kb = os.path.getsize(out_path) / 1024.0
    print(f"[OK] C Header exported to: {out_path} ({size_kb:.2f} KB)")
    return out_path


def main():
    deploy_dir = os.path.join(os.path.dirname(__file__), "artifacts")
    os.makedirs(deploy_dir, exist_ok=True)

    config_path = os.path.join(os.path.dirname(__file__), "..", "config", "fl_config.yaml")
    import yaml
    with open(config_path, "r") as f:
        config = yaml.safe_load(f)

    # Build model & load trained weights if available
    model = build_model(config["model"])
    model_path = os.path.join(os.path.dirname(__file__), "..", "results", "models", "model_fp32.pt")
    if os.path.exists(model_path):
        model.load_state_dict(torch.load(model_path, map_location="cpu"))
        print(f"Loaded trained model weights from: {model_path}")

    threshold = 0.0384
    summary_path = os.path.join(os.path.dirname(__file__), "..", "results", "experiment_summary.json")
    if os.path.exists(summary_path):
        with open(summary_path, "r") as f:
            data = json.load(f)
            threshold = data.get("primary_client_evaluation", {}).get("threshold", threshold)

    sample_input = torch.randn(1, 16, 8)

    ts_path = os.path.join(deploy_dir, "edge_model_torchscript.pt")
    onnx_path = os.path.join(deploy_dir, "edge_model.onnx")
    c_path = os.path.join(deploy_dir, "edge_model_weights.h")

    export_torchscript(model, sample_input, ts_path)
    export_onnx(model, sample_input, onnx_path)
    export_c_header(model, threshold, c_path)

    print("\n[SUCCESS] All edge deployment formats generated in: deploy/artifacts/")


if __name__ == "__main__":
    main()

